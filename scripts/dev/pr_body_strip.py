#!/usr/bin/env python3
"""Remove footer lines (ai_footer_check.MARKS) from a pull request body, then re-run a failed guard job.

    python3 scripts/dev/pr_body_strip.py              (pr-body.yml; GH_TOKEN, GITHUB_REPOSITORY, PR, HEAD_SHA)
    python3 scripts/dev/pr_body_strip.py --selftest
"""
import json
import os
import sys
import time
import urllib.request

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
try: import _argguard; _argguard.guard(__file__)  # --help and bad flags exit before any work
except ImportError: pass
sys.path[0] = os.path.dirname(os.path.abspath(__file__))
from ai_footer_check import found, strip  # noqa: E402

API = os.environ.get("GITHUB_API_URL", "https://api.github.com")


def call(method, path, token, data=None):
    req = urllib.request.Request(API + path, method=method,
                                 data=None if data is None else json.dumps(data).encode(),
                                 headers={"Authorization": "Bearer " + token,
                                          "Accept": "application/vnd.github+json",
                                          "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        raw = r.read()
        return json.loads(raw) if raw else None


def new_body(body):
    """The body without footer lines, or None when there is nothing to remove."""
    if not found(body or ""):
        return None
    return strip(body)


def guard_run(repo, sha, token):
    """(run id, guard job conclusion or None while it runs) for the newest pr-checks run of sha."""
    runs = call("GET", "/repos/%s/actions/workflows/pr-checks.yml/runs?head_sha=%s&per_page=5" % (repo, sha), token)
    for run in (runs or {}).get("workflow_runs", []):
        jobs = call("GET", "/repos/%s/actions/runs/%d/jobs?per_page=100" % (repo, run["id"]), token)
        for job in (jobs or {}).get("jobs", []):
            if job.get("name") == "guard":
                return run["id"], (job.get("conclusion") if job.get("status") == "completed" else None)
    return None, None


def main():
    repo, n, sha, token = (os.environ.get(k, "") for k in ("GITHUB_REPOSITORY", "PR", "HEAD_SHA", "GH_TOKEN"))
    if not (repo and n and token):
        print("no pull request in this run")
        return 0
    pr = call("GET", "/repos/%s/pulls/%s" % (repo, n), token) or {}
    body = new_body(pr.get("body"))
    if body is None:
        print("body has no footer lines")
        return 0
    call("PATCH", "/repos/%s/pulls/%s" % (repo, n), token, {"body": body})
    after = (call("GET", "/repos/%s/pulls/%s" % (repo, n), token) or {}).get("body") or ""
    if found(after):
        print("::error::the footer came back after the edit")
        return 1
    print("footer lines removed")
    sha = sha or (pr.get("head") or {}).get("sha", "")
    for _ in range(40):                      # up to about 10 minutes for the guard job to finish
        run_id, concl = guard_run(repo, sha, token)
        if run_id and concl:
            if concl == "failure":
                call("POST", "/repos/%s/actions/runs/%d/rerun-failed-jobs" % (repo, run_id), token)
                print("guard re-run started (run %d)" % run_id)
            else:
                print("guard: %s" % concl)
            return 0
        time.sleep(15)
    print("guard did not finish in time; it reads the body when it runs")
    return 0


def selftest():
    fails = 0
    cases = [
        ("Fixes X.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_1)_\n", "Fixes X."),
        ("Fixes X.\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_1",
         "Fixes X."),
        ("Lines like Generated by Claude Code inside prose stay.", None),
        ("", None),
    ]
    for text, want in cases:
        got = new_body(text)
        ok = got == want
        fails += not ok
        print(("ok    " if ok else "FAIL  ") + repr(text[:40]) + " -> " + repr(got))
    print("FAILS=%d" % fails)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(selftest() if "--selftest" in sys.argv[1:] else main())
